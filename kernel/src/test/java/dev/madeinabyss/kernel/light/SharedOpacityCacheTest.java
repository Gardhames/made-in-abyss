package dev.madeinabyss.kernel.light;

import java.util.Random;
import java.util.concurrent.*;
import java.util.concurrent.atomic.AtomicInteger;
import org.junit.jupiter.api.Test;
import static org.junit.jupiter.api.Assertions.*;

class SharedOpacityCacheTest {
    @Test void symmetricSkyPageLatticeUsesAvailableSharedCacheCapacity() {
        var cache=new SharedOpacityCache(32768);
        for(int y=-8;y<=8;y++)for(int z=-16;z<=16;z++)for(int x=-16;x<=16;x++)cache.getOrCompute(x*8,y*8,z*8,(xx,yy,zz)->0);
        assertTrue(cache.residentPages()>13500,"18513 distinct symmetric pages must not collapse into signed XOR pairs");
        assertTrue(cache.evictions()<5013);assertTrue(cache.residentBytes()<=17_170_432);
    }
    @Test void concurrentIdenticalCellsAreSampledOnce() throws Exception {
        var cache=new SharedOpacityCache(32768);var count=new AtomicInteger();
        SkyVisibility.VoxelOpacity source=(x,y,z)->{count.incrementAndGet();return 7;};
        var pool=Executors.newFixedThreadPool(8);var start=new CountDownLatch(1);
        try {
            var futures=new java.util.ArrayList<Future<Integer>>();
            for(int i=0;i<8;i++)futures.add(pool.submit(()->{start.await();int value=0;
                for(int j=0;j<1000;j++)value=cache.getOrCompute(-17,-4096,23,source);return value;}));
            start.countDown();for(var future:futures)assertEquals(7,future.get(10,TimeUnit.SECONDS));
            assertEquals(1,count.get(),"Immutable voxel must not be regenerated by each worker");
        }finally {pool.shutdownNow();}
    }
    @Test void randomizedRayOracleRetainsThinWallsAndPartialTransmission() {
        var random=new Random(940311);
        for(int i=0;i<120;i++){
            int shift=i%2==0?0:-20000,roof=shift-4-random.nextInt(12),wall=shift+random.nextInt(11)-5;
            SkyVisibility.VoxelOpacity oracle=(x,y,z)->y==roof&&x<wall?15:y==shift?4:
                x==wall&&z<shift-2?8:0;
            var cache=new SharedOpacityCache(512);
            SkyVisibility.VoxelOpacity cached=(x,y,z)->cache.getOrCompute(x,y,z,oracle);
            int x=shift+random.nextInt(31)-15,y=shift-32,z=shift+random.nextInt(31)-15;
            double expected=SkyVisibility.visibleFraction(x,y,z,shift+16,10000,oracle);
            assertEquals(expected,SkyVisibility.visibleFraction(x,y,z,shift+16,10000,cached));
            assertEquals(SkyVisibility.diffuseLevel(expected),QuantizedDiffuseSky.level(x,y,z,shift+16,10000,cached,false));
        }
    }
    @Test void invalidAndUnknownValuesNeverBecomeCachedGeometry() {
        var cache=new SharedOpacityCache(1);var calls=new AtomicInteger();
        SkyVisibility.VoxelOpacity unknown=(x,y,z)->{calls.incrementAndGet();throw new IllegalStateException("UNKNOWN");};
        for(int i=0;i<2;i++)assertThrows(IllegalStateException.class,()->cache.getOrCompute(-1,-1,-1,unknown));
        assertEquals(2,calls.get());
        assertThrows(IllegalArgumentException.class,()->cache.getOrCompute(-1,-1,-1,(x,y,z)->16));
        assertEquals(0,cache.getOrCompute(-1,-1,-1,(x,y,z)->0));
        assertEquals(0,cache.getOrCompute(-1,-1,-1,unknown));
    }
    @Test void extremeCoordinatesEvictionAndIndependentSourceIdentity() {
        var cache=new SharedOpacityCache(1);var edited=new SharedOpacityCache(1);
        int[] starts={Integer.MIN_VALUE,Integer.MIN_VALUE+7,-17,-8,-1,0,7,8,Integer.MAX_VALUE-7,Integer.MAX_VALUE};
        for(int coordinate:starts)assertEquals(9,cache.getOrCompute(coordinate,coordinate,coordinate,(x,y,z)->9));
        assertEquals(15,edited.getOrCompute(Integer.MAX_VALUE,Integer.MAX_VALUE,Integer.MAX_VALUE,(x,y,z)->15));
        assertEquals(9,cache.getOrCompute(Integer.MAX_VALUE,Integer.MAX_VALUE,Integer.MAX_VALUE,(x,y,z)->0));
        assertThrows(IllegalArgumentException.class,()->new SharedOpacityCache(3));
        assertThrows(IllegalArgumentException.class,()->new SharedOpacityCache(65536));
    }
    @Test void invalidCollisionRetainsExistingPageAndMemoryRemainsBounded() {
        var cache=new SharedOpacityCache(1);
        assertEquals(0,cache.residentBytes());
        assertThrows(IllegalStateException.class,()->cache.getOrCompute(0,0,0,(x,y,z)->{throw new IllegalStateException();}));
        assertEquals(0,cache.residentPages());
        assertEquals(3,cache.getOrCompute(-8,-16,-24,(x,y,z)->3));
        assertThrows(IllegalArgumentException.class,()->cache.getOrCompute(80,80,80,(x,y,z)->-1));
        assertEquals(3,cache.getOrCompute(-8,-16,-24,(x,y,z)->15));
        assertEquals(0,cache.evictions());
        for(int i=0;i<10000;i++){
            int value=i&15;
            assertEquals(value,cache.getOrCompute(i*8,i*8,-i*8,(x,y,z)->value));
        }
        assertEquals(1,cache.residentPages());assertEquals(524,cache.residentBytes());
        assertEquals(1,cache.capacity());assertTrue(cache.evictions()>=9999);
    }
    @Test void concurrentCollidingCoordinatesNeverAlias() throws Exception {
        var cache=new SharedOpacityCache(4);var pool=Executors.newFixedThreadPool(8);
        try {
            var futures=new java.util.ArrayList<Future<?>>();
            for(int worker=0;worker<8;worker++){
                int index=worker;
                futures.add(pool.submit(()->{
                    for(int i=0;i<10000;i++){
                        int x=i*8,y=index*8-20000,z=-i*8,expected=(i+index)&15;
                        assertEquals(expected,cache.getOrCompute(x,y,z,(xx,yy,zz)->expected));
                    }
                }));
            }
            for(var future:futures)future.get(20,TimeUnit.SECONDS);
            assertTrue(cache.residentPages()<=4);assertTrue(cache.residentBytes()<=4*524);
        }finally {pool.shutdownNow();}
    }
    @Test void publishedHitDoesNotWaitForUnrelatedSlowSampling() throws Exception {
        var cache=new SharedOpacityCache(1);var pool=Executors.newFixedThreadPool(2);
        var entered=new CountDownLatch(1);var release=new CountDownLatch(1);
        cache.getOrCompute(-8,-8,-8,(x,y,z)->4);
        try {
            var pending=pool.submit(()->cache.getOrCompute(80,80,80,(x,y,z)->{
                entered.countDown();try {release.await();}catch(InterruptedException e){Thread.currentThread().interrupt();throw new IllegalStateException(e);}return 8;
            }));
            assertTrue(entered.await(2,TimeUnit.SECONDS));
            var hit=pool.submit(()->cache.getOrCompute(-8,-8,-8,(x,y,z)->15));
            assertEquals(4,hit.get(500,TimeUnit.MILLISECONDS),"Published exact hit must not block behind another page's generator");
            release.countDown();assertEquals(8,pending.get(2,TimeUnit.SECONDS));
        }finally {release.countDown();pool.shutdownNow();}
    }
}

